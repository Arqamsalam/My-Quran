// Resolves tools/why_src.js entries to word positions and writes why.js.
// Run from the repository root: node tools/build_why.js
const fs = require('fs');
global.window = {};
for (const f of fs.readdirSync('.').filter(f => /^verses.*\.js$/.test(f))) require('../' + f);
require('../roots_core.js');
const VB = window.VERSES_BY_SURAH; VB[2] = window.VERSES; VB[3] = window.VERSES_3;
const WJ = window.WORD_JOIN || {};
const strip = t => t.replace(/[ً-ٰٟۖ-ࣰۭ-ࣲـ۞۩]/g, '').replace(/ٱ/g, 'ا');
const out = {}; let bad = 0;
for (const [s, v, find, note] of require('./why_src.js')) {
  const verse = VB[s] && VB[s][v];
  if (!verse) { console.log('NO VERSE', s, v); bad++; continue; }
  const t = verse.ar.split(' '), j = WJ[s + ':' + v];
  if (j) t.splice(j[0] - 1, j[1] - j[0] + 1, t.slice(j[0] - 1, j[1]).join(' '));
  const hits = t.map((w, i) => [strip(w), i]).filter(([w]) => w === find || w.endsWith(find) && w.length - find.length <= 2);
  const exact = hits.filter(([w]) => w === find);
  const use = exact.length === 1 ? exact : hits;
  // the same word repeated in one verse (e.g. ramayta … ramayta): the note covers every occurrence
  const same = use.length > 1 && use.every(([w]) => w === use[0][0]);
  if (!use.length || (use.length > 1 && !same)) { console.log('AMBIGUOUS/NOT FOUND', s, v, find, use.map(x => x[0])); bad++; continue; }
  for (const [, i] of use) out[`${s}:${v}:${i + 1}`] = note;
}
fs.writeFileSync('why.js', '// Curated "Why this word?" (balagha) notes, keyed surah:verse:word. Generated by tools/build_why.js from tools/why_src.js.\nwindow.WHY = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('notes', Object.keys(out).length, 'problems', bad);
